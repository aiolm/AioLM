/* global process */
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, renameSync, rmSync, symlinkSync, truncateSync, utimesSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { observeNativeBuildInputs, rustDependencyPaths } from "./native-build-inputs.mjs";

const SOURCE = "a".repeat(40);
const UNIT = "1".repeat(16);
const GENERATED_UNIT = "2".repeat(16);
const CHECKSUM = "b".repeat(64);
const PRIVATE = "SYNTHETIC_PRIVATE_SETTING";
const escapeMake = text => text.replaceAll("\\", "\\\\").replaceAll(" ", "\\ ").replaceAll("#", "\\#").replaceAll("$", "$$");
const fingerprint = features => `{"rustc":18446744073709551615,"features":${JSON.stringify(JSON.stringify(features))},"profile":12345678901234567890,"config":9876543210987654321,"compile_kind":0,"local":[{"env":"${PRIVATE}"}],"rustflags":["${PRIVATE}"]}`;

function fixture(t) {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "aiolm inputs # ")));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const target = join(root, ".codex-target");
  const unit = join(target, "debug", ".fingerprint", `aiolm-${UNIT}`);
  const generated = join(target, "debug", "build", `aiolm-${GENERATED_UNIT}`, "out", CHECKSUM);
  mkdirSync(unit, { recursive: true });
  mkdirSync(dirname(generated), { recursive: true });
  mkdirSync(join(target, "debug", "deps"), { recursive: true });
  writeFileSync(join(unit, "lib-aiolm_lib.json"), fingerprint(["default", "test-fixtures"]));
  const invocation = join(unit, "invoked.timestamp");
  writeFileSync(invocation, "");
  writeFileSync(generated, "synthetic icon bytes\n");
  utimesSync(invocation, 2, 2);
  utimesSync(generated, 3, 3);
  const depInfo = join(target, "debug", "deps", `aiolm_lib-${UNIT}.d`);
  writeFileSync(depInfo, `${escapeMake(join(target, "debug", "deps", "libaiolm_lib.rlib"))}: src/lib.rs ${escapeMake(generated)}\n${escapeMake(generated)}:\n# env-dep:AIOLM_BENCHMARK_API_URL=https://synthetic-private.invalid/${PRIVATE}\n`);
  const observe = (phase = "before") => observeNativeBuildInputs({ root, targetDirectory: target, sourceSha: SOURCE, phase, readSource: () => SOURCE });
  return { root, target, unit, generated, invocation, depInfo, observe };
}

test("the default normal library retains exact integer identities and declared generated-input timing", t => {
  const f = fixture(t);
  const value = f.observe();
  assert.equal(value.status, "observed");
  assert.deepEqual(value.unit, { id: UNIT, features: ["default", "test-fixtures"], profileId: "12345678901234567890", compilerId: "18446744073709551615", configId: "9876543210987654321", compileKind: "0", invocationNs: "2000000000" });
  assert.deepEqual(value.generatedInputs, [{ path: `debug/build/aiolm-${GENERATED_UNIT}/out/${CHECKSUM}`, sizeBytes: 21, sha256: createHash("sha256").update("synthetic icon bytes\n").digest("hex"), mtimeNs: "3000000000", newerThanInvocation: true, deltaNs: "1000000000" }]);
  assert.equal(value.sourceSha, SOURCE);
  assert.equal(value.phase, "before");
});

test("after observation distinguishes a later compile reference from unchanged generated bytes", t => {
  const f = fixture(t);
  const before = f.observe();
  utimesSync(f.invocation, 4, 4);
  const after = f.observe("after");
  assert.equal(after.unit.id, before.unit.id);
  assert.equal(after.generatedInputs[0].sha256, before.generatedInputs[0].sha256);
  assert.equal(after.generatedInputs[0].mtimeNs, before.generatedInputs[0].mtimeNs);
  assert.equal(after.generatedInputs[0].deltaNs, "-1000000000");
  assert.equal(after.generatedInputs[0].newerThanInvocation, false);
});

test("make dep-info handles escaped names, continuations, Windows drives and ignores environment comments", () => {
  const text = "C:/build/out.rlib: C:/source/lib.rs /with\\ space/icon\\#name \\\n /with\\\\slash/file /cash$$file\r\n# env-dep:PRIVATE=/must/not/be/read\n/with\\ space/icon\\#name:\n";
  assert.deepEqual(rustDependencyPaths(text), ["C:/source/lib.rs", "/with space/icon#name", "/with\\slash/file", "/cash$file"]);
});

test("private environment records and unrelated absolute dependencies are never emitted or opened", t => {
  const f = fixture(t);
  const secret = join(dirname(f.generated), "c".repeat(64));
  writeFileSync(secret, PRIVATE);
  writeFileSync(f.depInfo, readFileSync(f.depInfo, "utf8") + `# env-dep:PRIVATE=${escapeMake(secret)}\nignored-target: ${escapeMake(join(f.root, PRIVATE, "absent-file"))}\n`);
  const value = f.observe();
  assert.equal(value.status, "observed");
  assert.equal(value.generatedInputs.length, 1);
  assert.ok(!JSON.stringify(value).includes(PRIVATE));
  assert.ok(!JSON.stringify(value).includes(f.root));
  assert.ok(!JSON.stringify(value).includes("synthetic-private.invalid"));
});

test("missing and ambiguous normal libraries remain explicitly unavailable", t => {
  const f = fixture(t);
  const other = join(f.target, "debug", ".fingerprint", `aiolm-${"3".repeat(16)}`);
  mkdirSync(other);
  copyFileSync(join(f.unit, "lib-aiolm_lib.json"), join(other, "lib-aiolm_lib.json"));
  copyFileSync(f.invocation, join(other, "invoked.timestamp"));
  assert.equal(f.observe().reason, "ambiguous-default-library");
  rmSync(other, { recursive: true });
  rmSync(join(f.unit, "lib-aiolm_lib.json"));
  assert.equal(f.observe().reason, "missing-default-library");
});

test("all-feature and fixture-free UI variants cannot replace the requested default library", t => {
  const f = fixture(t);
  for (const features of [["default", "macos-ui-smoke", "test-fixtures"], ["macos-ui-smoke"], ["default", "test-fixtures", PRIVATE]]) {
    writeFileSync(join(f.unit, "lib-aiolm_lib.json"), fingerprint(features));
    const value = f.observe();
    assert.equal(value.reason, "missing-default-library");
    assert.ok(!JSON.stringify(value).includes(PRIVATE));
  }
});

test("malformed fingerprints and missing generated inputs do not expose diagnostic contents", t => {
  const f = fixture(t);
  writeFileSync(join(f.unit, "lib-aiolm_lib.json"), `${PRIVATE} not JSON`);
  assert.deepEqual(f.observe(), { formatVersion: 1, sourceSha: SOURCE, phase: "before", status: "unavailable", reason: "unreadable-native-inputs" });
  writeFileSync(join(f.unit, "lib-aiolm_lib.json"), fingerprint(["default", "test-fixtures"]));
  rmSync(f.generated);
  assert.equal(f.observe().status, "unavailable");
});

test("generated symlink directories cannot redirect observation outside the target tree", t => {
  const f = fixture(t);
  const outside = join(f.root, PRIVATE);
  mkdirSync(outside);
  writeFileSync(join(outside, CHECKSUM), PRIVATE);
  renameSync(dirname(f.generated), dirname(f.generated) + "-owned");
  symlinkSync(outside, dirname(f.generated), process.platform === "win32" ? "junction" : "dir");
  const value = f.observe();
  assert.equal(value.status, "unavailable");
  assert.equal(value.reason, "unsafe-input-file");
  assert.ok(!JSON.stringify(value).includes(PRIVATE));
});

test("oversized generated files and empty allowlists cannot become successful observations", t => {
  const f = fixture(t);
  truncateSync(f.generated, 67_108_865);
  assert.equal(f.observe().reason, "invalid-input-size");
  writeFileSync(f.depInfo, `ignored: ${escapeMake(join(f.root, "outside"))}\n# env-dep:PRIVATE=${escapeMake(f.generated)}\n`);
  assert.equal(f.observe().reason, "no-generated-inputs");
});

test("checkout provenance and phase validation fail before reading native metadata", t => {
  const f = fixture(t);
  const options = { root: f.root, targetDirectory: f.target, sourceSha: SOURCE, phase: "before", readSource: () => "b".repeat(40) };
  assert.throws(() => observeNativeBuildInputs(options), /source does not match/);
  assert.throws(() => observeNativeBuildInputs({ ...options, sourceSha: PRIVATE }), /Invalid native observation arguments/);
  assert.throws(() => observeNativeBuildInputs({ ...options, phase: PRIVATE }), /Invalid native observation arguments/);
});

test("library enumeration and aggregate fingerprint reads stay bounded", t => {
  const f = fixture(t);
  const parent = dirname(f.unit);
  for (let index = 0; index < 64; index += 1) mkdirSync(join(parent, `aiolm-${index.toString(16).padStart(16, "0")}`));
  assert.equal(f.observe().reason, "too-many-library-entries");
  for (let index = 0; index < 64; index += 1) rmSync(join(parent, `aiolm-${index.toString(16).padStart(16, "0")}`), { recursive: true });
  const data = fingerprint(["default", "test-fixtures"]).replace('"local":[', `"boundedPadding":"${"x".repeat(983_040)}","local":[`);
  for (let index = 0; index < 9; index += 1) {
    const folder = join(parent, `aiolm-${index.toString(16).padStart(16, "0")}`);
    mkdirSync(folder);
    writeFileSync(join(folder, "lib-aiolm_lib.json"), data);
    copyFileSync(f.invocation, join(folder, "invoked.timestamp"));
  }
  assert.equal(f.observe().reason, "invalid-input-size");
});

test("generated content hashing has an aggregate byte budget", t => {
  const f = fixture(t);
  const paths = [f.generated, join(dirname(f.generated), "c".repeat(64)), join(dirname(f.generated), "d".repeat(64))];
  for (const path of paths) { writeFileSync(path, ""); truncateSync(path, 12_582_912); }
  writeFileSync(f.depInfo, `target: ${paths.map(escapeMake).join(" ")}\n`);
  assert.equal(f.observe().reason, "invalid-input-size");
});

test("the CLI writes only the bounded snapshot and never echoes paths or invalid private arguments", t => {
  const f = fixture(t);
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const head = spawnSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" });
  assert.equal(head.status, 0);
  const output = join(f.root, "observation.json");
  const script = join(root, "scripts", "native-build-inputs.mjs");
  const env = { ...process.env, CARGO_TARGET_DIR: f.target };
  const good = spawnSync(process.execPath, [script, "--source", head.stdout.trim(), "--phase", "before", "--output", output], { cwd: root, env, encoding: "utf8" });
  assert.ifError(good.error);
  assert.equal(good.status, 0, good.stderr);
  assert.equal(JSON.parse(readFileSync(output)).status, "observed");
  assert.ok(!good.stdout.includes(f.root));
  assert.equal(good.stderr, "");
  writeFileSync(output, "preserved");
  const bad = spawnSync(process.execPath, [script, "--source", PRIVATE, "--phase", "before", "--output", output], { cwd: root, env, encoding: "utf8" });
  assert.ifError(bad.error);
  assert.equal(bad.status, 1);
  assert.equal(bad.stderr.trim(), "Native build input observation failed.");
  assert.equal(readFileSync(output, "utf8"), "preserved");
});
